"""
File: variables.py
Description: Demonstrates variables and data types.
"""

# Integer
age = 21

# Float
salary = 55000.50

# String
name = "Charan"

# Boolean
is_student = True

# List
skills = ["Python", "SQL", "Git"]

# Tuple
coordinates = (17.3850, 78.4867)

# Dictionary
vehicle = {
    "brand": "Tata",
    "model": "Nexon EV",
    "battery": "40 kWh"
}

print("Name:", name)
print("Age:", age)
print("Salary:", salary)
print("Student:", is_student)
print("Skills:", skills)
print("Coordinates:", coordinates)
print("Vehicle:", vehicle)