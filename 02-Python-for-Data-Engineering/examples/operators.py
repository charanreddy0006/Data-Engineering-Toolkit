"""
File: operators.py
Description: Demonstrates Python operators.
"""

a = 20
b = 6

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Power:", a ** b)

print()

print("Greater Than:", a > b)
print("Equal:", a == b)
print("Not Equal:", a != b)

print()

